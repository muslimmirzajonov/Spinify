    static func resolvedCode() -> String {
        if let saved = UserDefaults.standard.string(forKey: "spinify_lang_code"),
           supported.contains(where: { $0.code == saved }) {
            return saved
        }
        let preferred = Locale.preferredLanguages
        for lang in preferred {
            if let match = supported.first(where: { lang.hasPrefix($0.code) }) {
                return match.code
            }
        }
        return "en"
    }
    
